"""Export one CSV per Gold and Silver-mirror table (capped) into samples/, read-only against Databricks.

  docker compose run --rm spark python scripts/export_samples.py [--out samples] [--rows 10000] [--tables a,b]

Only SELECT statements are run, through the store interface. raw_payload is never exported. The data is synthetic.
"""
import argparse
import csv
import os
import sys
from datetime import date, datetime
from decimal import Decimal
from pathlib import Path

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

from warehouse.store import StoreConfigError, get_store
from warehouse.tables import all_tables

DEFAULT_LIMIT = 10_000
NEVER_EXPORT = ("raw_payload",)
SENTENCE = ("Synthetic data generated by the FunnelStream simulator (seed 7 universe). "
            "Capped at 10,000 rows per table.")


def _text(v):
    if v is None:
        return ""
    if isinstance(v, Decimal):
        return format(v, "f")
    if isinstance(v, (datetime, date)):
        return v.isoformat()
    if isinstance(v, bool):
        return "true" if v else "false"
    return v


def export_rows(rows, path, limit=DEFAULT_LIMIT):
    """Write at most `limit` rows (dicts) to a UTF-8 CSV. An empty list writes an empty file. Returns the path."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = list(rows)[:limit]
    with open(path, "w", newline="", encoding="utf-8") as fh:
        if rows:
            w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
            w.writeheader()
            for r in rows:
                w.writerow({k: _text(v) for k, v in r.items()})
    return path


def export_columns(spec):
    return [c for c in spec.column_names() if c not in NEVER_EXPORT]


def select_sql(store, spec, rows):
    cols = export_columns(spec)
    order = [k for k in spec.keys if k in cols] or cols  # a keyless table is ordered by all its columns
    return "SELECT %s FROM %s ORDER BY %s LIMIT %d" % (", ".join(cols), store.qualified(spec.name),
                                                        ", ".join(order), rows)


def write_readme(out, entries):
    lines = ["# Sample data", "", SENTENCE, "", "| File | Rows | Columns |", "|---|---|---|"]
    for name, n, ncols in entries:
        lines.append("| %s.csv | %d | %d |" % (name, n, ncols))
    (Path(out) / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv=None, store=None):
    ap = argparse.ArgumentParser(description="Export capped CSV samples of the Gold and Silver mirror tables.")
    ap.add_argument("--out", default="samples")
    ap.add_argument("--rows", type=int, default=DEFAULT_LIMIT)
    ap.add_argument("--tables", help="comma separated subset (default: every table)")
    try:
        args = ap.parse_args(argv)
    except SystemExit as e:
        return 2 if e.code else 0
    specs = {t.name: t for t in all_tables()}
    names = [t.strip() for t in args.tables.split(",") if t.strip()] if args.tables else list(specs)
    unknown = [n for n in names if n not in specs]
    if args.rows < 1 or unknown:
        print("error: %s" % ("--rows must be at least 1" if args.rows < 1 else "unknown table(s): " + ", ".join(unknown)),
              file=sys.stderr)
        return 2
    own = store is None
    try:
        if own:
            store = get_store("databricks")
    except StoreConfigError as e:
        print("error: %s" % e, file=sys.stderr)
        return 2
    entries = []
    try:
        for name in names:
            spec = specs[name]
            cols = export_columns(spec)
            result = store.query(select_sql(store, spec, args.rows))
            rows = [dict(zip(cols, r)) for r in result]
            export_rows(rows, Path(args.out) / (name + ".csv"), args.rows)
            entries.append((name, min(len(rows), args.rows), len(cols)))
            print("%s: %d rows" % (name, entries[-1][1]))
        write_readme(args.out, entries)
    except Exception as e:
        token = os.environ.get("DATABRICKS_TOKEN") or ""
        text = " ".join(str(e).split())[:300]
        print("error: export failed (%s): %s" % (type(e).__name__, text.replace(token, "***") if token else text),
              file=sys.stderr)
        return 1
    finally:
        if own and store is not None:
            store.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
