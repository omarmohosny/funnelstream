def test_no_personal_columns_in_exported_tables():
    allowed = {("silver_products", "name"), ("dim_product", "name"), ("dim_campaign", "name")}
    bad = [(t.name, c) for t in all_tables() for c in ex.export_columns(t)
           if c in ("name", "phone", "email", "address") and (t.name, c) not in allowed]
    assert bad == []
    assert all("raw_payload" not in ex.export_columns(t) for t in all_tables())


