SENTENCE = ("Synthetic data generated by the FunnelStream simulator (seed 7 universe). "
            "Capped at 10,000 rows per table.")


def _read(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.reader(fh))


class FakeStore:
    def __init__(self, counts=None, fail=False):
        self.sql = []
        self.counts = counts or {}
        self.fail = fail
        self.closed = False

    def qualified(self, name):
        return "cat.%s.%s" % ("x", name)

    def query(self, sql, params=None, retry=True):
        self.sql.append(sql)
        if self.fail:
            raise RuntimeError("boom")
        table = sql.split(" FROM ")[1].split()[0].split(".")[-1]
        spec = next(t for t in all_tables() if t.name == table)
        n = min(self.counts.get(table, 3), int(sql.rsplit("LIMIT ", 1)[1]))
        cols = [c for c in spec.columns if c.name != "raw_payload"]
        return [tuple(("v%d" % i) if c.type == "string" else None for c in cols) for i in range(n)]

    def close(self):
        self.closed = True


def test_export_rows_caps_at_limit(tmp_path):
    rows = [{"a": i, "b": "x"} for i in range(25_000)]
    p = ex.export_rows(rows, tmp_path / "t.csv")
    data = _read(p)
    assert len(data) == 1 + 10_000
    assert data[0] == ["a", "b"]
    assert data[-1] == ["9999", "x"]


def test_export_rows_fewer_than_limit_and_custom_limit(tmp_path):
    assert len(_read(ex.export_rows([{"a": 1}, {"a": 2}], tmp_path / "a.csv"))) == 3
    assert len(_read(ex.export_rows([{"a": i} for i in range(9)], tmp_path / "b.csv", limit=4))) == 5


def test_export_rows_empty_writes_empty_file_and_returns_path(tmp_path):
    p = ex.export_rows([], tmp_path / "deep" / "dir" / "e.csv")
    assert p.exists() and p.read_text() == ""


def test_export_rows_plain_text_for_money_dates_and_none(tmp_path):
    rows = [{"m": Decimal("1E+2"), "r": Decimal("0.5000"), "d": date(2026, 10, 1),
             "t": datetime(2026, 10, 1, 12, 30, 5), "n": None, "b": True}]
    data = _read(ex.export_rows(rows, tmp_path / "f.csv"))
    assert data[1] == ["100", "0.5000", "2026-10-01", "2026-10-01T12:30:05", "", "true"]


def test_sql_has_explicit_columns_order_by_keys_limit_and_qualified_name(tmp_path):
    store = FakeStore()
    assert ex.main(["--out", str(tmp_path), "--rows", "50", "--tables", "fact_order_lines"], store=store) == 0
    sql = store.sql[0]
    spec = next(t for t in all_tables() if t.name == "fact_order_lines")
    assert sql == "SELECT %s FROM cat.x.fact_order_lines ORDER BY order_id, line_no LIMIT 50" % ", ".join(
        spec.column_names())
    assert "*" not in sql


def test_sql_never_selects_raw_payload_and_keyless_table_orders_by_columns(tmp_path):
    store = FakeStore()
    assert ex.main(["--out", str(tmp_path), "--tables", "silver_quarantine"], store=store) == 0
    sql = store.sql[0]
    assert "raw_payload" not in sql
    assert "ORDER BY" in sql and sql.endswith("LIMIT 10000")


def test_main_writes_one_csv_per_table_and_readme(tmp_path, capsys):
    store = FakeStore(counts={"dim_date": 0, "agg_orders_daily": 5})
    assert ex.main(["--out", str(tmp_path), "--tables", "dim_date,agg_orders_daily"], store=store) == 0
    out = capsys.readouterr().out
    assert "dim_date: 0 rows" in out and "agg_orders_daily: 5 rows" in out
    assert (tmp_path / "dim_date.csv").read_text() == ""
    assert len(_read(tmp_path / "agg_orders_daily.csv")) == 6
    readme = (tmp_path / "README.md").read_text(encoding="utf-8")
    assert SENTENCE in readme
    assert "agg_orders_daily.csv" in readme and "dim_date.csv" in readme
    spec = next(t for t in all_tables() if t.name == "agg_orders_daily")
    line = next(l for l in readme.splitlines() if "agg_orders_daily.csv" in l)
    assert "| 5 |" in line and "| %d |" % len(spec.columns) in line


