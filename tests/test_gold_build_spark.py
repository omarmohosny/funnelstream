def put_order(spark, env, oid, customer, created, statuses=(("order_created", 0),), total="100.00", items=1,
              channel="paid_search"):
    load(spark, env.silver, "silver_orders", [order_row(oid, customer=customer, created=created, total=total,
                                                         channel=channel)])
    rows = []
    for status, hours in statuses:
        when = created.replace(tzinfo=timezone.utc) if hours == 0 else datetime.fromtimestamp(
            created.timestamp() + hours * 3600, tz=timezone.utc)
        rows.append(status_row(oid, status, when, carrier="aramex" if status == "order_shipped" else None,
                               customer=customer))
    load(spark, env.silver, "silver_order_status", rows)
    load(spark, env.silver, "silver_order_items", [
        {"order_id": oid, "line_no": str(i + 1), "product_id": "p1", "quantity": 1,
         "unit_price": Decimal("10.00"), "line_total": Decimal("10.00"), "currency": "EGP", "order_time": created}
        for i in range(items)])


def snapshot(spark, env, tables=("fact_orders", "fact_order_lines", "agg_orders_daily", "agg_funnel_daily")):
    return {n: sorted(map(tuple, spark.table("%s.%s" % (env.gold, n)).collect()), key=repr) for n in tables}


def test_unknown_customer_gets_minus_one_and_a_later_build_repairs_it(spark, env):
    seed_dims(spark, env, customers=("c1",))
    put_order(spark, env, "o_known", "c1", t(1, 10))
    put_order(spark, env, "o_new", "c_new", t(1, 11))
    run_build(env, steps=ORD, **MONTH)
    keys = {r["order_id"]: r["customer_key"] for r in spark.table(env.gold + ".fact_orders").collect()}
    c1_key = spark.sql("SELECT customer_key FROM %s.dim_customer WHERE customer_id = 'c1'" % env.gold).first()[0]
    assert keys == {"o_known": c1_key, "o_new": -1}
    assert {r["customer_key"] for r in spark.table(env.gold + ".fact_order_lines").collect()} == {c1_key, -1}
    # the customer row arrives in Silver: the next build (same window) repairs the -1 in facts and lines
    load(spark, env.silver, "silver_customers", [{
        "customer_id": "c_new", "updated_at": datetime(2025, 1, 1), "country": "EG", "city": "Giza",
        "district": "Dokki", "signup_date": date(2025, 1, 1), "primary_device": "desktop",
        "marketing_consent": False}])
    run_build(env, from_date="2026-10-01", to_date="2026-10-01", steps=ORD)
    new_key = spark.sql("SELECT customer_key FROM %s.dim_customer WHERE customer_id = 'c_new'" % env.gold).first()[0]
    assert new_key not in (None, -1)
    keys = {r["order_id"]: r["customer_key"] for r in spark.table(env.gold + ".fact_orders").collect()}
    assert keys == {"o_known": c1_key, "o_new": new_key}
    lines = {r["order_id"]: r["customer_key"] for r in spark.table(env.gold + ".fact_order_lines").collect()}
    assert lines == {"o_known": c1_key, "o_new": new_key}


def test_late_status_row_changes_that_order_and_its_day_only(spark, env):
    seed_dims(spark, env)
    put_order(spark, env, "o1", "c1", t(1, 10), [("order_created", 0), ("order_shipped", 2)], total="100.00")
    put_order(spark, env, "o2", "c2", t(2, 10), [("order_created", 0), ("order_shipped", 2)], total="200.00")
    put_order(spark, env, "o3", "c1", t(3, 10), [("order_created", 0)], total="300.00")
    run_build(env, steps=ORD, **MONTH)
    before = snapshot(spark, env)
    # a late delivered row for o1 (placed Oct 1) arrives with status_time Oct 5
    load(spark, env.silver, "silver_order_status", [status_row("o1", "delivered", t(5, 9), customer="c1")])
    run_build(env, from_date="2026-10-05", to_date="2026-10-05", steps=REBUILD)
    after = snapshot(spark, env)
    fo_b, fo_a = {r[0]: r for r in before["fact_orders"]}, {r[0]: r for r in after["fact_orders"]}
    changed = sorted(k for k in fo_a if fo_a[k] != fo_b[k])
    assert changed == ["o1"]
    assert spark.sql("SELECT is_delivered FROM %s.fact_orders WHERE order_id = 'o1'" % env.gold).first()[0] is True
    assert before["fact_order_lines"] == after["fact_order_lines"]
    assert before["agg_funnel_daily"] == after["agg_funnel_daily"]
