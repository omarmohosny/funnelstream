def test_dim_customer_scd2_versions_collapse_per_day_and_track_only_tracked_attributes(spark, env):
    far = datetime(9999, 12, 31)
    load(spark, env.silver, "silver_customers", [
        cust("a", datetime(2026, 1, 1, 8)),
        cust("a", datetime(2026, 2, 1, 8), city="Giza", district="Dokki"),
        cust("a", datetime(2026, 2, 1, 9), city="Giza", district="Agouza"),   # same day: this one wins
        cust("a", datetime(2026, 3, 1, 8), city="Giza", district="Agouza", consent=False),  # not tracked
        cust("a", datetime(2026, 4, 1, 8), city="Giza", district="Agouza", device="desktop"),
        cust("b", datetime(2026, 1, 1, 8))])
    run_build(env, steps=["dim_customer"], full=True)
    assert dim_versions(spark, env, "a") == [
        (datetime(2026, 1, 1, 8), datetime(2026, 2, 1, 9), False, "Cairo", "Maadi"),
        (datetime(2026, 2, 1, 9), datetime(2026, 4, 1, 8), False, "Giza", "Agouza"),
        (datetime(2026, 4, 1, 8), far, True, "Giza", "Agouza")]
    assert dim_versions(spark, env, "b") == [(datetime(2026, 1, 1, 8), far, True, "Cairo", "Maadi")]
    keys = [r[0] for r in spark.sql("SELECT customer_key FROM %s.dim_customer" % env.gold).collect()]
    assert len(keys) == len(set(keys)) == 5 and -1 in keys
    before = snapshot(spark, env, ("dim_customer",))
    run_build(env, steps=["dim_customer"], full=True)
    assert snapshot(spark, env, ("dim_customer",)) == before  # MERGE keeps keys and rows
    # a new version arrives: the old current row is closed (valid_to, is_current only), the new one is inserted
    load(spark, env.silver, "silver_customers", [cust("b", datetime(2026, 5, 1, 8), city="Tanta", district="Tanta First")])
    run_build(env, steps=["dim_customer"], full=True)
    assert dim_versions(spark, env, "b") == [
        (datetime(2026, 1, 1, 8), datetime(2026, 5, 1, 8), False, "Cairo", "Maadi"),
        (datetime(2026, 5, 1, 8), far, True, "Tanta", "Tanta First")]
    # a second change on the same day after the first run of that day: the earlier row is closed, never two current
    load(spark, env.silver, "silver_customers", [cust("b", datetime(2026, 5, 1, 12), city="Assiut", district="Assiut First")])
    run_build(env, steps=["dim_customer"], full=True)
    v = dim_versions(spark, env, "b")
    assert [x[2] for x in v] == [False, False, True] and v[1][1] == v[2][0] == datetime(2026, 5, 1, 12)


