class SparkStore(GoldStore):
    """TEST ONLY GoldStore over a local Spark session; assigns the keys Delta OSS cannot generate."""

    def __init__(self, spark, silver, gold):
        self.spark, self.silver, self.gold = spark, silver, gold
        self.executed = []

    def schema_prefix(self, group):
        return {"silver": self.silver, "gold": self.gold}[group]

    def upsert(self, table, rows, key_cols):
        raise NotImplementedError

    def query(self, sql, params=None, retry=True):
        return [tuple(r) for r in self.spark.sql(sql).collect()]

    def execute(self, sql, retry=True):
        self.executed.append(sql)
        self.spark.sql(sql)
        m = re.match(r"MERGE INTO %s\.(dim_customer|dim_product|dim_campaign)\b" % re.escape(self.gold), sql)
        if m:
            self._assign_keys(m.group(1))

    def _assign_keys(self, table):
        key, natural = DIM_NATURAL[table]
        full = "%s.%s" % (self.gold, table)
        if self.spark.sql("SELECT 1 FROM %s WHERE %s IS NULL LIMIT 1" % (full, key)).count() == 0:
            return
        cols = ", ".join(natural)
        on = " AND ".join("t.%s = s.%s" % (c, c) for c in natural)
        self.spark.sql(
            "MERGE INTO %s t USING (SELECT %s, (SELECT GREATEST(COALESCE(MAX(%s), 0), 0) FROM %s) "
            "+ ROW_NUMBER() OVER (ORDER BY %s) AS k FROM %s WHERE %s IS NULL) s ON %s "
            "WHEN MATCHED THEN UPDATE SET t.%s = s.k" % (full, cols, key, full, cols, full, key, on, key))

    def close(self):
        pass


def make_env(spark, location, silver, gold, with_unknown=True, gold_tables=GOLD_NEEDED):
    """Schemas with plain-BIGINT-key copies of the real DDL; unknown members seeded like apply_ddl does."""
    for schema in (silver, gold):
        spark.sql("DROP SCHEMA IF EXISTS %s CASCADE" % schema)
        spark.sql("CREATE SCHEMA %s LOCATION '%s/%s'" % (schema, location, schema))
    wanted = set(SILVER_FACTS) | set(gold_tables) | {"silver_campaign_snapshots"}  # empty unless a test fills it
    for stmt in split_statements(render_databricks(all_tables(), catalog="funnelstream")):
        m = re.match(r"CREATE TABLE IF NOT EXISTS funnelstream\.(\w+)\.(\w+) \(", stmt)
        if not m or m.group(2) not in wanted:
            continue
        stmt = (stmt.replace("funnelstream.gold.", gold + ".").replace("funnelstream.silver.", silver + ".")
                .replace(" GENERATED BY DEFAULT AS IDENTITY", ""))
        spark.sql(stmt)
    store = SparkStore(spark, silver, gold)
    if with_unknown:
        for stmt in seed_statements("databricks", "funnelstream"):
            store.execute(stmt.replace("funnelstream.gold.", gold + "."))
    return store


def load(spark, silver, table, rows=None, df=None):
    """Append rows (dicts, Silver schema) or a DataFrame to the Silver mirror table."""
    df = df if df is not None else mk(spark, table, rows)
    cols = [f.name for f in SCHEMAS[table].fields]
    df.select(*cols).write.format("delta").mode("append").insertInto("%s.%s" % (silver, table))


def table_rows(spark, schema, table, key_cols):
    cols = spark.table("%s.%s" % (schema, table)).columns
    rows = [tuple(r) for r in spark.table("%s.%s" % (schema, table)).collect()]
    idx = [cols.index(k) for k in key_cols]
    return cols, {tuple(r[i] for i in idx): r for r in rows}


def same(a, b, tol=None):
    if a is None or b is None:
        return a is None and b is None
    if tol is not None and isinstance(a, (Decimal, float)) and isinstance(b, (Decimal, float)):
        return abs(Decimal(str(a)) - Decimal(str(b))) <= tol
    return a == b


def compare(sql_df, ref_df, keys, columns, tol=None):
    """Full outer join on keys in Python: (rows_sql, rows_ref, only_sql, only_ref, {column: mismatches}, samples)."""
    def to_map(df):
        out, n = {}, 0
        for r in df.collect():
            d = r.asDict()
            out[tuple(d[k] for k in keys)] = d
            n += 1
        return out, n

    (a, n_a), (b, n_b) = to_map(sql_df), to_map(ref_df)
    assert n_a == len(a) and n_b == len(b), "duplicate keys: %d rows, %d distinct (sql); %d, %d (reference)" % (
        n_a, len(a), n_b, len(b))
    mism = {c: 0 for c in columns}
    samples = []
    for k in a.keys() & b.keys():
        for c in columns:
            if not same(a[k][c], b[k][c], tol if c in ("cart_abandon_rate", "checkout_abandon_rate") else None):
                mism[c] += 1
                if len(samples) < 5:
                    samples.append((k, c, a[k][c], b[k][c]))
    return n_a, n_b, len(a.keys() - b.keys()), len(b.keys() - a.keys()), mism, samples


