def test_dates_are_right_when_the_session_time_zone_is_not_utc(spark, env):
    """The build pins the session zone to UTC itself: without it date_key / event_date would shift."""
    seed_dims(spark, env)
    # 22:30 UTC on Oct 1 is 01:30 on Oct 2 in Cairo (UTC+3 until the end of October)
    put_order(spark, env, "late_night", "c1", t(1, 22, 30), [("order_created", 0), ("order_shipped", 1)])
    load(spark, env.silver, "silver_events", [ev(1, "s1", t(1, 22, 30), "product_view")])
    spark.conf.set("spark.sql.session.timeZone", "America/Los_Angeles")
    try:
        result = run_build(env, steps=["dim_customer", "dim_product", "fact_orders", "fact_order_lines",
                                       "agg_orders_daily", "agg_funnel_daily"], full=True)
        assert spark.conf.get("spark.sql.session.timeZone") == "UTC"  # the pin took effect for the session
    finally:
        spark.conf.set("spark.sql.session.timeZone", "UTC")
    assert result["steps"]["fact_orders"]["rows"] == 1
    got = spark.sql("SELECT date_key FROM %s.fact_orders" % env.gold).first()[0]
    assert got == 20261002
    assert spark.sql("SELECT date_key FROM %s.fact_order_lines" % env.gold).first()[0] == 20261002
    assert spark.sql("SELECT date_key FROM %s.agg_orders_daily" % env.gold).first()[0] == 20261002
    # silver event_date was written by the test (UTC date); the funnel keeps it as is
    assert spark.sql("SELECT event_date FROM %s.agg_funnel_daily" % env.gold).first()[0] == date(2026, 10, 1)
