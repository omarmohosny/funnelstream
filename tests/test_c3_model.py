def test_identity_is_by_default_in_both_dialects():
    pg = ddl_render.render_postgres(all_tables())
    dbx = ddl_render.render_databricks(all_tables())
    for key in ("customer_key", "product_key", "campaign_key"):
        assert "%s bigint GENERATED BY DEFAULT AS IDENTITY" % key in pg
        assert "%s BIGINT GENERATED BY DEFAULT AS IDENTITY" % key in dbx
    assert "ALWAYS" not in pg and "ALWAYS" not in dbx
    assert dbx.count("GENERATED BY DEFAULT AS IDENTITY") == 3


def test_unknown_rows_exactly_three_dimensions_with_key_minus_one():
    assert tuple(UNKNOWN_ROWS) == DIMS
    assert "dim_date" not in UNKNOWN_ROWS
    for dim, row in UNKNOWN_ROWS.items():
        t = gold_table(dim)
        assert set(row) <= set(t.column_names())
        assert row[t.keys[0]] == -1
        for c in t.columns:  # every NOT NULL column has a value
            if not c.nullable:
                assert row[c.name] is not None, (dim, c.name)
    c = UNKNOWN_ROWS["dim_customer"]
    assert c["customer_id"] == "unknown" and c["is_current"] is True and c["marketing_consent"] is False
    assert UNKNOWN_ROWS["dim_product"]["name"] == "Unknown" and UNKNOWN_ROWS["dim_product"]["is_active"] is False
    assert UNKNOWN_ROWS["dim_product"]["price"] == 0
    assert (c["valid_from"].year, c["valid_to"].year) == (1900, 9999)


def test_seed_statements_databricks_text():
    stmts = seed_statements("databricks", "workspace")
    assert len(stmts) == 3
    s = stmts[0]
    assert s.startswith("MERGE INTO workspace.gold.dim_customer AS t USING (SELECT -1 AS customer_key, ")
    assert "'unknown' AS customer_id" in s
    assert "TIMESTAMP '1900-01-01 00:00:00+00:00' AS valid_from" in s
    assert "TIMESTAMP '9999-12-31 00:00:00+00:00' AS valid_to" in s
    assert "ON t.customer_key = s.customer_key WHEN NOT MATCHED THEN INSERT (customer_key, customer_id, " in s
    assert "WHEN MATCHED" not in s
    assert re.search(r"VALUES \(s\.customer_key, s\.customer_id, ", s)
    assert stmts[1].startswith("MERGE INTO workspace.gold.dim_product AS t USING (SELECT -1 AS product_key, ")
    assert "0 AS price" in stmts[1] and "FALSE AS is_active" in stmts[1] and "TRUE AS is_current" in stmts[1]
    assert stmts[2].startswith("MERGE INTO workspace.gold.dim_campaign AS t USING (SELECT -1 AS campaign_key, ")
    with pytest.raises(ValueError):
        seed_statements("databricks", "bad cat;")
    with pytest.raises(ValueError):
        seed_statements("mysql", "x")


def test_seed_statements_postgres_text_names_the_key_column():
    stmts = seed_statements("postgres", None)
    assert len(stmts) == 3
    for stmt, dim, key in zip(stmts, DIMS, ("customer_key", "product_key", "campaign_key")):
        assert stmt.startswith("INSERT INTO %s (%s, " % (dim, key)), stmt
        assert "VALUES (-1, " in stmt
        assert stmt.endswith("ON CONFLICT (%s) DO NOTHING" % key)
    assert "'1900-01-01 00:00:00+00'" in stmts[0] and "'9999-12-31 00:00:00+00'" in stmts[0]


class FakeStore:
    def __init__(self):
        self.executed = []

    def execute(self, sql, retry=True):
        self.executed.append(sql)

    def run_script(self, sql_text, retry=True):  # pragma: no cover - apply_ddl must not use it any more
        raise AssertionError("seeds need individual execute calls")

    def close(self):
        pass

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()


def test_apply_ddl_databricks_order_schemas_volume_tables_seeds(monkeypatch):
    fake = FakeStore()
    monkeypatch.setattr(apply_ddl, "get_store", lambda backend, env=None: fake)
    assert apply_ddl.main(["--backend", "databricks", "--catalog", "workspace"]) == 0
    ex = fake.executed
    assert ex[0].startswith("CREATE SCHEMA") and ex[1].startswith("CREATE SCHEMA")
    assert ex[2].startswith("CREATE VOLUME")
    tables = [s for s in ex if s.startswith("CREATE TABLE")]
    assert len(tables) == len(all_tables()) == 21
    assert ex[3:3 + len(tables)] == tables
    assert ex[3 + len(tables):] == seed_statements("databricks", "workspace")
    assert len(ex) == 3 + 21 + 3


def test_apply_ddl_postgres_script_then_seeds_and_dry_run_lists_seeds(monkeypatch, capsys):
    fake = FakeStore()
    monkeypatch.setattr(apply_ddl, "get_store", lambda backend, env=None: fake)
    assert apply_ddl.main(["--backend", "postgres"]) == 0
    assert fake.executed[0] == (ROOT / "warehouse" / "ddl.sql").read_text(encoding="utf-8")
    assert fake.executed[1:] == seed_statements("postgres", None)
    assert apply_ddl.main(["--backend", "postgres", "--dry-run"]) == 0
    out = capsys.readouterr().out
    assert "3 seed statements" in out and out.count("seed: INSERT INTO") == 3
    assert apply_ddl.main(["--backend", "databricks", "--catalog", "workspace", "--dry-run"]) == 0
    out = capsys.readouterr().out
    assert "databricks: 27 statements" in out and out.count("MERGE INTO workspace.gold.dim_") == 3


