def test_fact_order_lines_and_agg_columns_exact():
    assert gold_table("fact_order_lines").column_names() == [
        "order_id", "line_no", "customer_key", "customer_id", "product_key", "product_id", "date_key", "city",
        "quantity", "line_total"]
