"""Unknown members (spec section 17, rule 2): the -1 row of dim_customer, dim_product and dim_campaign.

A fact row with no matching dimension version stores key -1 instead of being quarantined; the daily Gold
build re-joins by natural id and repairs the -1 once the dimension row exists. The rows are seeded by
scripts/apply_ddl.py after the CREATE statements, idempotently (MERGE ... WHEN NOT MATCHED on Databricks,
INSERT ... ON CONFLICT DO NOTHING on Postgres). The surrogate keys are GENERATED BY DEFAULT AS IDENTITY, so the
explicit key -1 is accepted; normal rows never supply a key. Columns that are None are left out of the INSERT
(dates with no sensible unknown value stay NULL). dim_date has no unknown member.
"""
from datetime import datetime, timezone
from decimal import Decimal

from warehouse.store import _ident, sql_literal

UNKNOWN_KEY = -1
VALID_FROM = datetime(1900, 1, 1, tzinfo=timezone.utc)
VALID_TO = datetime(9999, 12, 31, tzinfo=timezone.utc)

# table -> (key column, ordered {column: value}); the key column comes first and holds -1
UNKNOWN_ROWS = {
    "dim_customer": {
        "customer_key": UNKNOWN_KEY, "customer_id": "unknown", "country": "unknown", "city": "unknown",
        "signup_date": None, "primary_device": "unknown", "marketing_consent": False,
        "valid_from": VALID_FROM, "valid_to": VALID_TO, "is_current": True,
    },
    "dim_product": {
        "product_key": UNKNOWN_KEY, "product_id": "unknown", "name": "Unknown", "category": "unknown",
        "price": Decimal("0"), "is_active": False, "valid_from": VALID_FROM, "valid_to": VALID_TO,
        "is_current": True,
    },
    "dim_campaign": {
        "campaign_key": UNKNOWN_KEY, "campaign_id": "unknown", "utm_campaign": "unknown", "platform": "unknown",
        "name": "Unknown", "start_date": None, "end_date": None,
    },
}


def key_column(table):
    return next(iter(UNKNOWN_ROWS[table]))


def _row(table):
    return {c: v for c, v in UNKNOWN_ROWS[table].items() if v is not None}


def _pg_literal(value):
    if isinstance(value, datetime):
        return "'%s+00'" % value.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
    if isinstance(value, str):
        return "'%s'" % value.replace("'", "''")
    return sql_literal(value)


def _dbx_literal(value):
    if isinstance(value, datetime):
        return "TIMESTAMP '%s+00:00'" % value.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
    return sql_literal(value)


def seed_statements(dialect, catalog):
    """One idempotent statement per unknown member, in UNKNOWN_ROWS order. dialect: databricks or postgres."""
    out = []
    for table in UNKNOWN_ROWS:
        key, row = key_column(table), _row(table)
        cols = [_ident(c) for c in row]
        if dialect == "databricks":
            cat = _ident(catalog)
            src = ", ".join("%s AS %s" % (_dbx_literal(v), c) for c, v in row.items())
            out.append("MERGE INTO %s.gold.%s AS t USING (SELECT %s) AS s ON t.%s = s.%s "
                       "WHEN NOT MATCHED THEN INSERT (%s) VALUES (%s)"
                       % (cat, table, src, key, key, ", ".join(cols), ", ".join("s." + c for c in cols)))
        elif dialect == "postgres":
            out.append("INSERT INTO %s (%s) VALUES (%s) ON CONFLICT (%s) DO NOTHING"
                       % (table, ", ".join(cols), ", ".join(_pg_literal(v) for v in row.values()), key))
        else:
            raise ValueError("unknown dialect %r" % (dialect,))
    return out
